<?php

namespace App\Http\Controllers;

use App\Services\AccessControl;
use App\Services\Pdf\ReportPdfBuilder;
use App\Services\ReportDefinitions;
use Illuminate\Http\Request;

class ReportController extends Controller
{
    private const MAX_EXPORT_ROWS = 3000;

    public function index(string $module, Request $request)
    {
        $definition = $this->resolveDefinition($module);

        $filters = [
            'status' => $request->query('status'),
            'date_from' => $request->query('date_from'),
            'date_to' => $request->query('date_to'),
        ];

        $query = AccessControl::scopeApplications($definition['model']::query());
        $query = ReportDefinitions::applyFilters($query, $filters);

        $totalCount = (clone $query)->count();
        $records = $query->orderByDesc('created_at')->paginate(15)->withQueryString();

        $rows = $records->getCollection()->map($definition['map']);

        return view('reports.index', [
            'module' => $module,
            'moduleLabel' => ReportDefinitions::modules()[$module],
            'definition' => $definition,
            'filters' => $filters,
            'records' => $records,
            'rows' => $rows,
            'totalCount' => $totalCount,
        ]);
    }

    public function exportPdf(string $module, Request $request)
    {
        $definition = $this->resolveDefinition($module);

        $filters = [
            'status' => $request->query('status'),
            'date_from' => $request->query('date_from'),
            'date_to' => $request->query('date_to'),
        ];

        $query = AccessControl::scopeApplications($definition['model']::query());
        $query = ReportDefinitions::applyFilters($query, $filters);

        $records = $query->orderByDesc('created_at')->limit(self::MAX_EXPORT_ROWS)->get();
        $rows = $records->map($definition['map'])->map(fn ($row) => (array) $row)->all();

        $user = AccessControl::user();
        $roleName = $user?->role_name ?? 'System';
        $jurisdiction = collect([$user?->county, $user?->district])->filter()->implode(', ');
        $generatedBy = trim("Generated by {$roleName}" . ($jurisdiction ? " — {$jurisdiction}" : '') . ($user ? " ({$user->full_name})" : ''));

        $filterLabels = [
            'Status' => !empty($filters['status']) ? ucfirst($filters['status']) : null,
            'From' => $filters['date_from'] ?: null,
            'To' => $filters['date_to'] ?: null,
        ];

        $builder = new ReportPdfBuilder();
        $pdfContent = $builder->build(
            $definition['title'],
            $generatedBy,
            $filterLabels,
            $definition['columns'],
            $rows
        );

        Helper::auditTrail(
            'Report Exported (PDF)',
            'Report',
            null,
            'success',
            null,
            ['module' => $module, 'rows' => count($rows)],
            "Exported the {$definition['title']} as PDF (" . count($rows) . ' rows).'
        );

        $filename = $module . '-report-' . now()->format('Ymd-His') . '.pdf';

        return response($pdfContent, 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
            'Content-Length' => strlen($pdfContent),
        ]);
    }

    private function resolveDefinition(string $module): array
    {
        if (!array_key_exists($module, ReportDefinitions::modules())) {
            abort(404, 'Unknown report.');
        }

        $definition = ReportDefinitions::for($module);

        if (!AccessControl::can($definition['permission'])) {
            abort(403, 'You do not have permission to view this report.');
        }

        return $definition;
    }
}
